create table if not exists public.careers (
    id bigint generated by default as identity primary key,
    nombre varchar(150) not null unique,
    duracion varchar(50) not null,
    modalidad varchar(50) not null,
    descripcion text not null
);

create table if not exists public.recommendations (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    career_id bigint not null references public.careers(id) on delete cascade,
    puntaje numeric(5, 2) not null check (puntaje between 0 and 100),
    resultado varchar(100) not null,
    constraint uq_recommendations_user_career unique (user_id, career_id)
);

create index if not exists idx_recommendations_career_id
    on public.recommendations(career_id);

-- Proteccion inicial en Supabase: sin politicas de acceso publico.
alter table public.careers enable row level security;
alter table public.recommendations enable row level security;
