create table if not exists public.test_questions (
    id bigint generated by default as identity primary key,
    enunciado text not null,
    categoria varchar(100) not null
);

create table if not exists public.test_answers (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    question_id bigint not null references public.test_questions(id) on delete cascade,
    respuesta varchar(255) not null,
    constraint uq_test_answers_user_question unique (user_id, question_id)
);

create table if not exists public.learning_routes (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    career_id bigint not null references public.careers(id) on delete cascade,
    estado varchar(50) not null,
    progreso numeric(5, 2) not null default 0
        check (progreso between 0 and 100),
    constraint uq_learning_routes_user_career unique (user_id, career_id)
);

create index if not exists idx_test_answers_question_id
    on public.test_answers(question_id);

create index if not exists idx_learning_routes_career_id
    on public.learning_routes(career_id);

-- Protección inicial en Supabase.
-- No se crean políticas de acceso público en esta etapa del TP9.
alter table public.test_questions enable row level security;
alter table public.test_answers enable row level security;
alter table public.learning_routes enable row level security;