create table if not exists public.profiles (
    id bigint generated by default as identity primary key,
    user_id bigint not null unique references public.users(id) on delete cascade,
    intereses varchar(255) not null,
    habilidades varchar(255) not null
);

create table if not exists public.favorites (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    career_id bigint not null references public.careers(id) on delete cascade,
    constraint uq_favorites_user_career unique (user_id, career_id)
);

create index if not exists idx_favorites_career_id
    on public.favorites(career_id);

alter table public.profiles enable row level security;
alter table public.favorites enable row level security;
